import { languageModules } from "@/app/data/content";
import type {
  ProblemDefinition,
  StudyConcept,
  StudyDrill,
  StudyUnitDefinition,
} from "@/app/data/problem-definition";

type ConceptSeed = [
  cue: string,
  signal: string,
  direction: string,
  example: string,
  meaning: string,
  wrong?: string,
  variants?: string[],
];

type DrillSeed = [
  cue: string,
  choices: string[],
  answer: number,
  reason: string,
];

type UnitSeed = {
  slug: string;
  title: string;
  japanese: string;
  minutes: number;
  objective: string;
  summary: [string, string, string];
  focus: string[];
  tip: string;
  concepts: ConceptSeed[];
  traps: [string, string][];
  drills: DrillSeed[];
};

function concept(seed: ConceptSeed): StudyConcept {
  const [cue, signal, direction, example, exampleMeaning, wrong, variants] = seed;
  return { cue, signal, direction, example, exampleMeaning, wrong, variants };
}

function makeUnit(problem: string, index: number, seed: UnitSeed): StudyUnitDefinition {
  const number = String(index + 1).padStart(2, "0");
  return {
    id: `${problem}-${seed.slug}`,
    slug: seed.slug,
    number,
    title: seed.title,
    japanese: seed.japanese,
    estimatedMinutes: seed.minutes,
    objective: seed.objective,
    summary: seed.summary,
    coverage: seed.focus,
    noteInsight: seed.tip,
    concepts: seed.concepts.map(concept),
    traps: seed.traps.map(([title, contrast]) => ({ title, contrast })),
    drills: seed.drills.map<StudyDrill>(([cue, choices, answer, reason], drillIndex) => ({
      id: `${problem}-${seed.slug}-${drillIndex + 1}`,
      cue,
      choices,
      answer,
      reason,
    })),
    relatedContentIds: [`${problem}-${seed.slug}`],
    sourceRefs: [`complete-notes/${problem}.json`],
  };
}

